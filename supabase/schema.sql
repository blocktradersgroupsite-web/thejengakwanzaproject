-- 1. Settings Table
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- 2. Users / Workers Table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'Cashier',
    phone TEXT,
    pin_hash TEXT NOT NULL,
    active INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Work Shifts & Attendance Table ("Who was working on that specific day")
CREATE TABLE IF NOT EXISTS work_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    work_date DATE NOT NULL,
    clock_in TIMESTAMPTZ DEFAULT NOW(),
    clock_out TIMESTAMPTZ,
    opening_cash NUMERIC(15,2) DEFAULT 0.00,
    closing_cash NUMERIC(15,2),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Products & Stock Table
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT UNIQUE,
    barcode TEXT,
    name TEXT NOT NULL,
    category TEXT DEFAULT 'General',
    unit TEXT DEFAULT 'pcs',
    cost_price NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    selling_price NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    stock_quantity NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    min_alert_quantity NUMERIC(15,2) NOT NULL DEFAULT 5.00,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Stock Movements Audit Log
CREATE TABLE IF NOT EXISTS stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    product_name TEXT,
    movement_type TEXT NOT NULL,
    quantity NUMERIC(15,2) NOT NULL,
    balance_after NUMERIC(15,2) NOT NULL,
    unit_cost NUMERIC(15,2) DEFAULT 0.00,
    reference_id TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Customers Table
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT,
    email TEXT,
    address TEXT,
    credit_limit NUMERIC(15,2) DEFAULT 0.00,
    current_credit NUMERIC(15,2) DEFAULT 0.00,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Suppliers Table
CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    contact_person TEXT,
    phone TEXT,
    email TEXT,
    address TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Orders Table (POS, Commercial Invoices, Proformas)
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    order_type TEXT NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT,
    subtotal NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    discount NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    tax NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    total NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    payment_method TEXT NOT NULL DEFAULT 'CASH',
    payment_status TEXT NOT NULL DEFAULT 'PAID',
    amount_paid NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    balance_due NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    due_date DATE,
    notes TEXT,
    items JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Delivery Notes Table
CREATE TABLE IF NOT EXISTS delivery_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_number TEXT UNIQUE NOT NULL,
    order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT,
    delivery_address TEXT NOT NULL,
    transporter_name TEXT,
    vehicle_number TEXT,
    dispatched_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    delivery_date DATE,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Purchase Orders Table
CREATE TABLE IF NOT EXISTS purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number TEXT UNIQUE NOT NULL,
    supplier_id BIGINT REFERENCES suppliers(id) ON DELETE RESTRICT,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    subtotal NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    tax NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    status TEXT NOT NULL DEFAULT 'PENDING',
    expected_date DATE,
    received_date TIMESTAMPTZ,
    notes TEXT,
    items JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Daily Expenses Table
CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_number TEXT UNIQUE NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    category TEXT NOT NULL,
    amount NUMERIC(15,2) NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'CASH',
    description TEXT NOT NULL,
    expense_date DATE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. Debtor Payments (Credit Repayments) Table
CREATE TABLE IF NOT EXISTS debtor_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_number TEXT UNIQUE NOT NULL,
    customer_id BIGINT REFERENCES customers(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    amount NUMERIC(15,2) NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'CASH',
    payment_date DATE NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 13. Capital & Cash Ledger Table
CREATE TABLE IF NOT EXISTS capital_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_type TEXT NOT NULL,
    amount NUMERIC(15,2) NOT NULL,
    account TEXT NOT NULL DEFAULT 'CASH',
    description TEXT NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    entry_date DATE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

